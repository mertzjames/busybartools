#!/usr/bin/env python3
"""Render every scene and write all outputs.

    python3 renderer/build.py [--no-gif] [--only owl_post,...]

Outputs
  app/src/animations/<scene>.anim      firmware-played animations (+ clock_bg.anim)
  app/shared/generated/show.ts         playlist, durations, fonts, clock layout for the JS app
  mockup/index.html                    self-contained browser simulator + storyboards
  previews/<scene>.gif                 LED-style GIF previews

Every .anim is decoded again and compared pixel-for-pixel with the rendered frames.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

from PIL import Image  # noqa: E402

import font  # noqa: E402
from anim_writer import image_to_bgra, read_anim, write_anim  # noqa: E402
from canvas import FPS, H, W, flatten  # noqa: E402
from preview import led  # noqa: E402
from scenes import CLOCK_BG, PLAYLIST  # noqa: E402

APP_ID = "wizard.thanksgiving"

# Display tone curve (docs/DECISIONS.md D21). Applied to every output frame and to the clock colors, so the
# bar, the mockup and the storyboards all match. v' = 255 * (v/255) ** GAMMA. 1.0 = original colors;
# lower = brighter darks/midtones (black stays black, full brightness stays full). 0.8 = "a little brighter".
GAMMA = 0.8
_TONE = [min(255, int(255 * (v / 255) ** GAMMA + 0.5)) for v in range(256)]


def tone(img):
    return img.point(_TONE * 3)


def tone_rgb(c):
    return [_TONE[v] for v in c]


def clock_layout() -> dict:
    lay = json.loads(json.dumps(CLOCK_BG.LAYOUT))
    for key in ("time", "date"):
        for part in ("top", "bottom", "shadow"):
            lay[key][part] = tone_rgb(lay[key][part])
    return lay
ANIM_DIR = ROOT / "app" / "src" / "animations"
GEN_DIR = ROOT / "app" / "shared" / "generated"  # under shared/: bundled into main.js (src/*.ts become separate entries)
MOCKUP = ROOT / "mockup"
PREVIEWS = ROOT / "previews"


def encode(module, frames) -> dict:
    flat = [tone(flatten(f)) for f in frames]
    bgra = [image_to_bgra(f) for f in flat]
    path = ANIM_DIR / f"{module.NAME}.anim"
    size = write_anim(path, bgra, W, H, FPS)
    back = read_anim(path)
    assert back["width"] == W and back["height"] == H and back["fps"] == FPS
    assert len(back["frames"]) == len(bgra)
    for i, (a, b) in enumerate(zip(bgra, back["frames"])):
        assert a == b, f"{module.NAME}: frame {i} round-trip mismatch"
    return {"flat": flat, "bytes": size}


def sheet_b64(flat) -> str:
    """All frames stacked vertically into one PNG (data URI payload)."""
    sheet = Image.new("RGB", (W, H * len(flat)))
    for i, f in enumerate(flat):
        sheet.paste(f, (0, i * H))
    buf = io.BytesIO()
    sheet.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def gif(name: str, flat) -> None:
    frames = [led(f, cell=5, gap=1) for f in flat]
    frames[0].save(PREVIEWS / f"{name}.gif", save_all=True, append_images=frames[1:], duration=int(1000 / FPS),
                   loop=0, optimize=True)


