// New Year's Eve: what the live screens look like (docs/DECISIONS.md D8-D10). Pure functions, no device calls.
//
// Each live screen is a list of layers (pixel-font text, optionally clipped, and solid rectangles) composed into ONE
// xpmbitmap, so every update is a single draw request. Text is drawn by the shared kit's textBitmap, so it matches
// busybar.font.draw_text pixel for pixel (tests/live_parity.py checks the composed bitmaps against the renderer).
// Like nye.ts, this file is inlined into the mockup: single-line imports only, no enums.

import { textBitmap, textWidth, type Bitmap, type Font, type TextSpec } from "../../../../lib/ts/busybar/xpmtext.ts";
import { secondsToMidnight, type LocalTime } from "../../../../lib/ts/busybar/walltime.ts";
import { cardText, celebrateState, finalText, finalBarPixels, newYear, phaseAt, secondsSinceMidnight, type StepKind } from "./nye.ts";

export const SCREEN_H = 16;
const SCREEN_WIDTH = 72;

export type Fonts = Record<string, Font>;

export interface TextLayer {
  kind: "text";
  text: string;
  spec: TextSpec;
  x: number;
  y: number;
  /** Optional clip rectangle [x0, y0, x1, y1) (the odometer windows). */
  clip?: readonly number[];
}
export interface RectLayer {
  kind: "rect";
  x: number;
  y: number;
  w: number;
  h: number;
  color: readonly number[];
}
export type Layer = TextLayer | RectLayer;

/** Generated by renderer/build.py (colors already tone-mapped). */
export interface Layout {
  card: { main: TextSpec; label: TextSpec; label_dy: number; gap: number };
  final: { count: TextSpec; bar: { y: number; h: number; on: readonly number[]; off: readonly number[] } };
  final10: { specs: readonly TextSpec[] };
  celebrate: { greeting: TextSpec; year: TextSpec; huge: TextSpec };
  odometer: { spec: TextSpec; windows: readonly number[]; win_y: number; win_w: number; win_h: number };
}

/** Live-step backdrops (keys of SHOW.bg). */
export type StageKey = "card" | "final" | "final_fast" | "final10" | "burst" | "fireworks";

/** The final-minute backdrop speeds up for the last 30 s. */
export const FAST_FROM_S = 30;

function centered(text: string, spec: TextSpec, fonts: Fonts): TextLayer {
  return { kind: "text", text, spec, x: Math.floor((SCREEN_WIDTH - textWidth(text, fonts[spec.font])) / 2), y: spec.y };
}

/** Countdown / clock card: the main line in the clock font, two small lines stacked to its right. */
export function cardLayers(main: string, top: string, bottom: string, L: Layout, fonts: Fonts): Layer[] {
  const c = L.card;
  const wm = textWidth(main, fonts[c.main.font]);
  const wt = textWidth(top, fonts[c.label.font]);
  const wb = textWidth(bottom, fonts[c.label.font]);
  const lw = Math.max(wt, wb);
  const x0 = Math.max(0, Math.floor((SCREEN_WIDTH - (wm + c.gap + lw)) / 2));
  const lx = x0 + wm + c.gap;
  return [
    { kind: "text", text: main, spec: c.main, x: x0, y: c.main.y },
    { kind: "text", text: top, spec: c.label, x: lx + Math.floor((lw - wt) / 2), y: c.label.y },
    { kind: "text", text: bottom, spec: c.label, x: lx + Math.floor((lw - wb) / 2), y: c.label.y + c.label_dy },
  ];
}

/** Final minute: the seconds left, big and centered, over a progress bar along the bottom row. */
export function finalLayers(remaining: number, L: Layout, fonts: Fonts): Layer[] {
  const b = L.final.bar;
  const lit = finalBarPixels(remaining, SCREEN_WIDTH);
  const layers: Layer[] = [{ kind: "rect", x: 0, y: b.y, w: SCREEN_WIDTH, h: b.h, color: b.off }];
  if (lit > 0) layers.push({ kind: "rect", x: 0, y: b.y, w: lit, h: b.h, color: b.on });
  layers.push(centered(finalText(remaining), L.final.count, fonts));
  return layers;
}

/** Final ten: one huge digit, a different color every second. */
export function final10Layers(remaining: number, L: Layout, fonts: Fonts): Layer[] {
  const specs = L.final10.specs;
  return [centered(String(remaining), specs[remaining % specs.length], fonts)];
}

export function celebrateLayers(text: "zero" | "none" | "greeting" | "year", year: number, L: Layout, fonts: Fonts): Layer[] {
  if (text === "zero") return final10Layers(0, L, fonts);
  if (text === "none") return [];
  if (text === "year") return [centered(String(year), L.celebrate.huge, fonts)];
  return [centered("HAPPY NEW YEAR", L.celebrate.greeting, fonts), centered(String(year), L.celebrate.year, fonts)];
}

/**
 * The year odometer: four windows; digits that change roll upward by `progress` (0 = old year, 1 = new year).
 */
export function odometerLayers(oldYear: number, nextYear: number, progress: number, L: Layout, fonts: Fonts): Layer[] {
  const o = L.odometer;
  const a = String(oldYear).slice(-4);
  const b = String(nextYear).slice(-4);
  const layers: Layer[] = [];
  const shift = Math.round(progress * o.win_h);
  for (let i = 0; i < o.windows.length; i++) {
    const wx = o.windows[i];
    const clip = [wx, o.win_y, wx + o.win_w, o.win_y + o.win_h];
    const font = fonts[o.spec.font];
    const put = (ch: string, y: number) => {
      const x = wx + Math.floor((o.win_w - textWidth(ch, font)) / 2);
      layers.push({ kind: "text", text: ch, spec: o.spec, x, y, clip });
    };
    if (a[i] === b[i] || progress <= 0) put(a[i], o.spec.y);
    else if (progress >= 1) put(b[i], o.spec.y);
    else {
      put(a[i], o.spec.y - shift);
      put(b[i], o.spec.y + o.win_h - shift);
    }
  }
  return layers;
}

/** A scene's live overlay at `ms` into the scene, or null (only the odometer has one). */
export interface Overlay {
  kind: "odometer";
  /** [ms into the scene, roll progress]: the overlay changes at each event. */
  events: readonly (readonly number[])[];
}

export function overlayAt(overlay: Overlay | undefined, ms: number, t: LocalTime, L: Layout, fonts: Fonts): Layer[] | null {
  if (!overlay) return null;
  let p = -1;
  for (const e of overlay.events) if (e[0] <= ms) p = e[1];
  if (p < 0) return null;
  const y = newYear(t);
  return odometerLayers(y - 1, y, p, L, fonts);
}

/** A live step's screen at effective time t: which backdrop plays and the text layers on top. */
export interface Screen {
  stage: StageKey;
  loop: boolean;
  layers: Layer[];
}

/**
 * Time-locked steps draw whatever the clock says now (a late tick may already be in the next phase); a "final" step
 * that starts before T-60 s (because no scene fits) shows "1:05" and so on. `startedAt` is the seconds since midnight
 * when a celebrate step began: the one-shot burst only plays if it began at 00:00:00.
 */
export function screenAt(kind: StepKind, t: LocalTime, startedAt: number, L: Layout, fonts: Fonts): Screen {
  if (kind !== "card" && kind !== "scene") {
    const ph = phaseAt(t);
    const r = secondsToMidnight(t);
    if (ph === "final10") return { stage: "final10", loop: true, layers: final10Layers(r, L, fonts) };
    if (ph === "final" || (kind === "final" && ph === "party")) {
      return { stage: r <= FAST_FROM_S ? "final_fast" : "final", loop: true, layers: finalLayers(r, L, fonts) };
    }
    if (ph === "celebrate") {
      const c = celebrateState(secondsSinceMidnight(t), startedAt);
      const burst = c.stage === "burst";
      return { stage: burst ? "burst" : "fireworks", loop: !burst, layers: celebrateLayers(c.text, newYear(t), L, fonts) };
    }
  }
  const c = cardText(t);
  return { stage: "card", loop: true, layers: cardLayers(c.main, c.top, c.bottom, L, fonts) };
}

// --- composing layers into one XPM2 bitmap ----------------------------------------------------------------------

const XPM_CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789#$%&*+-=@";

function colorHex(c: readonly number[]): string {
  let s = "#";
  for (let k = 0; k < 3; k++) {
    const v = Math.max(0, Math.min(255, Math.round(c[k]))).toString(16).toUpperCase();
    s += v.length < 2 ? "0" + v : v;
  }
  return s;
}

/** Paints layers onto a 72x16 grid of "#RRGGBB" strings ("" = transparent). Later layers draw on top. */
export function paintLayers(layers: readonly Layer[], fonts: Fonts): string[] {
  const px: string[] = [];
  for (let i = 0; i < SCREEN_WIDTH * SCREEN_H; i++) px.push("");
  for (const layer of layers) {
    if (layer.kind === "rect") {
      const c = colorHex(layer.color);
      for (let y = Math.max(0, layer.y); y < Math.min(SCREEN_H, layer.y + layer.h); y++) {
        for (let x = Math.max(0, layer.x); x < Math.min(SCREEN_WIDTH, layer.x + layer.w); x++) px[y * SCREEN_WIDTH + x] = c;
      }
      continue;
    }
    const bmp = textBitmap(layer.text, fonts[layer.spec.font], layer.spec, layer.x);
    const lines = bmp.data.split("\n");
    const n = Number(lines[1].split(" ")[2]);
    const pal: Record<string, string> = {};
    for (let k = 0; k < n; k++) {
      const parts = lines[2 + k].split(" ");
      if (parts[2] !== "none") pal[parts[0]] = parts[2];
    }
    const clip = layer.clip || [0, 0, SCREEN_WIDTH, SCREEN_H];
    for (let by = 0; by < bmp.height; by++) {
      const row = lines[2 + n + by];
      const y = layer.y + by;
      if (y < Math.max(0, clip[1]) || y >= Math.min(SCREEN_H, clip[3])) continue;
      for (let bx = 0; bx < bmp.width; bx++) {
        const c = pal[row[bx]];
        const x = layer.x + bx;
        if (!c || x < Math.max(0, clip[0]) || x >= Math.min(SCREEN_WIDTH, clip[2])) continue;
        px[y * SCREEN_WIDTH + x] = c;
      }
    }
  }
  return px;
}

/** Composes layers into one xpmbitmap, cropped to what's drawn; null when nothing is. At most 32 colors. */
export function composeBitmap(layers: readonly Layer[], fonts: Fonts): Bitmap | null {
  const px = paintLayers(layers, fonts);
  let x0 = SCREEN_WIDTH, y0 = SCREEN_H, x1 = -1, y1 = -1;
  for (let y = 0; y < SCREEN_H; y++) {
    for (let x = 0; x < SCREEN_WIDTH; x++) {
      if (!px[y * SCREEN_WIDTH + x]) continue;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  if (x1 < 0) return null;
  const chars: Record<string, string> = {};
  const colors: string[] = [". c none"];
  const rows: string[] = [];
  for (let y = y0; y <= y1; y++) {
    let row = "";
    for (let x = x0; x <= x1; x++) {
      const c = px[y * SCREEN_WIDTH + x];
      if (!c) {
        row += ".";
        continue;
      }
      if (!chars[c]) {
        if (colors.length >= 32) throw new Error("xpmbitmap: more than 32 colors");
        chars[c] = XPM_CHARS[colors.length - 1];
        colors.push(chars[c] + " c " + c);
      }
      row += chars[c];
    }
    rows.push(row);
  }
  const width = x1 - x0 + 1;
  const height = y1 - y0 + 1;
  const data = ["! XPM2", `${width} ${height} ${colors.length} 1`].concat(colors, rows).join("\n");
  return { data, width, height, x: x0, y: y0 };
}
