"""Scene: The Lone Bugler. A lone bugler stands on a low hill, silhouetted against the setting sun. He raises the
bugle and holds it while the sun goes down (taps is implied: no notes are drawn), then lowers it and stands at
attention as the light fades. A generic service cap and uniform: no insignia, no face."""

import math

from busybar.canvas import H, W, add, ease_in_out, mix, phase, put, sec
from busybar.sprite import Sprite
from mdfx import glow, quant, sky

NAME = "bugler"
TITLE = "The Lone Bugler"
SECONDS = 14
KEYFRAMES = [(1.0, "A bugler on the hill at sunset"), (4.0, "He raises the bugle"),
             (8.5, "The sun goes down"), (13.0, "At attention as the light fades")]

# Facing right: the silhouette (S, the bugle too, as against the sun) with a glint of brass at the bell (B).
# A faint warm rim along the top edges is added in code.
PAL = {"S": "#22182C", "B": "#F0C870"}
REST = """
..SS.....
.SSSS....
..SS.....
..SS.....
.SSSS....
.SSSS....
.SSSSS...
.SSSSB...
.SSS.....
.S.S.....
.S.S.....
.S.S.....
SS.SS....
"""
RAISED = """
..SS.......
.SSSS......
..SSSSSSS..
..SSS...SB.
.SSSS....B.
.SSS.......
.SSS.......
.SSS.......
.SSS.......
.S.S.......
.S.S.......
.S.S.......
SS.SS......
"""
LIFTING = """
..SS.....
.SSSS....
..SS.....
..SSS....
.SSSSSS..
.SSSS.SB.
.SSS.....
.SSS.....
.SSS.....
.S.S.....
.S.S.....
.S.S.....
SS.SS....
"""
POSES = {k: Sprite(k, PAL, g).img() for k, g in (("rest", REST), ("lift", LIFTING), ("raised", RAISED))}

FIG_X, FEET = 26, 13  # sprite left column; the row the feet stand on
SUN_X = 28.5

TOP = [(0, (74, 52, 116)), (6, (168, 92, 104)), (11, (236, 140, 84)), (13, (246, 164, 92))]
LATE = [(0, (40, 30, 84)), (6, (112, 62, 96)), (11, (184, 94, 72)), (13, (200, 110, 74))]


def hill(x: int) -> int:
    """Row of the hill's top edge at column x: a low mound under the bugler."""
    return int(math.floor(13 + 2.4 * ((x - 28) / 22) ** 2 + 0.5)) if abs(x - 28) < 22 else 15


def render():
    frames = []
    for f in range(sec(SECONDS)):
        late = quant(ease_in_out(phase(f, sec(2.0), sec(13.5))), 40)
        img = sky([(r, mix(a, b, late)) for (r, a), (_, b) in zip(TOP, LATE)])
        sy = 5.5 + 5.5 * late  # the sun sinks behind the hill, from behind his shoulders
        glow(img, SUN_X, sy, 20, (255, 150, 70), 0.5 * (1 - 0.4 * late), squash=1.3)
        for y in range(H):
            for x in range(W):
                d = math.hypot(x - SUN_X, (y - sy) * 1.1)
                if d <= 4.6:
                    put(img, x, y, mix((255, 236, 170), (255, 160, 80), d / 4.6), 1 - 0.2 * late)
        for x in range(W):
            for y in range(min(hill(x), 15), H):
                put(img, x, y, (34, 26, 44))
            # the far land along the horizon on either side of the hill
            if hill(x) >= 15:
                put(img, x, 14, (52, 36, 58))
        t = f / 15
        pose = "rest" if t < 2.6 or t >= 12.2 else ("lift" if t < 3.1 or t >= 11.7 else "raised")
        spr = POSES[pose]
        top = FEET - spr.height + 1
        img.alpha_composite(spr, (FIG_X, top))
        # a faint warm rim along the top edges of the silhouette, fading with the light
        rim = 0.22 * (1 - late)
        px = spr.load()
        for yy in range(spr.height):
            for xx in range(spr.width):
                if px[xx, yy][3] and px[xx, yy][:3] != (0xF0, 0xC8, 0x70):
                    edge = yy == 0 or not px[xx, yy - 1][3]
                    if edge:
                        add(img, FIG_X + xx, top + yy, (255, 150, 80), rim)
        frames.append(img)
    return frames
