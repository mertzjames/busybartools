EYE_DARK = "#4A2418"
EYE_GLINT = "#FFF0C0"


def walk(name: str, palette: dict, body: str, *legs: str) -> Sprite:
    """A sprite whose frames share the body rows and differ only in the leg rows."""
    return Sprite(name, palette, *[body.rstrip("\n") + "\n" + leg for leg in legs])


