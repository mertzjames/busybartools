"""Text-grid sprites (docs/DECISIONS.md D3, D5): the zodiac animals, the dance dragon's head, the lion dance lion,
and small props. Sprites face right; use img(i, flip=True) for left.

Small features use lit colors: black is an unlit LED, so eyes on light fur are a dark-but-lit brown and eyes on
darker fur are a light glint.
"""

from __future__ import annotations

